def build_user_prompt(payload: dict, retry_reason: str = "") -> str:
    specs = payload.get("specs") or {}
    specs_lines = "\n".join(f"- {k}: {v}" for k, v in specs.items()) or "- данных нет"

    prompt = f"""Исходные данные о товаре для генерации карточки:

Название: {payload.get('name') or 'данных нет'}
Производитель: {payload.get('manufacturer') or 'данных нет'}

Технические характеристики:
{specs_lines}

Исходное описание / техпаспорт:
{payload.get('description') or 'данных нет'}

Внимательно прочитай абсолютные запреты в системной инструкции. Выдай только JSON с 4 полями."""

    if retry_reason:
        prompt += f"\n\nВНИМАНИЕ! Твой предыдущий ответ был отклонен по причине: {retry_reason}. Исправь ошибку и верни корректный JSON."

    return prompt
